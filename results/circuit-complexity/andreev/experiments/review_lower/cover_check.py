"""Referee: independent computation of tau_m (min #lines such that every unit square of {0..m}^2 has a corner cut,
i.e. a line with exactly 1 or 3 of its 4 vertices on the positive side) and of its LP relaxation, plus the
same for UP-SETS (the class relevant to sign-coherent gates), via a different enumeration than the author's:
all line dichotomies are generated by sweeping GENERIC directions (midpoints between consecutive critical angles)
and taking every prefix of the sorted projections.  Exact cover via scipy.optimize.milp (HiGHS), LP via linprog."""
import sys, math, itertools
sys.path.insert(0, '/tmp/pydeps')
import numpy as np
from fractions import Fraction
from scipy.optimize import milp, LinearConstraint, Bounds, linprog

def line_dichotomies(m):
    V = [(a, b) for a in range(m + 1) for b in range(m + 1)]
    angs = set()
    for (p, q) in itertools.combinations(V, 2):
        dx, dy = q[0] - p[0], q[1] - p[1]
        # normal directions perpendicular to (dx,dy): angle of (-dy,dx) and its opposite
        for (nx, ny) in ((-dy, dx), (dy, -dx)):
            angs.add(math.atan2(ny, nx))
    angs = sorted(angs)
    gen = [(angs[i] + angs[i + 1]) / 2 for i in range(len(angs) - 1)] + [(angs[-1] + angs[0] + 2 * math.pi) / 2]
    P = np.array(V, dtype=float)
    out = set()
    for t in gen:
        u = np.array([math.cos(t), math.sin(t)])
        proj = P @ u; order = np.argsort(proj)
        side = np.zeros(len(V), dtype=bool)
        for r in range(len(V)):          # positive side = the r+1 largest projections
            side[order[len(V) - 1 - r]] = True
            out.add(side.tobytes())
    return V, [np.frombuffer(s, dtype=bool) for s in out]

def cutsets_from_sides(m, V, sides):
    idx = {v: i for i, v in enumerate(V)}
    sq = [(a, b) for a in range(m) for b in range(m)]
    C = np.array([[idx[(a, b)], idx[(a + 1, b)], idx[(a, b + 1)], idx[(a + 1, b + 1)]] for a, b in sq])
    sets = set()
    for s in sides:
        cnt = s[C].sum(1)
        cut = frozenset(np.nonzero((cnt == 1) | (cnt == 3))[0].tolist())
        if cut: sets.add(cut)
    sets = sorted(sets, key=len, reverse=True); maximal = []
    for s in sets:
        if not any(s <= t for t in maximal): maximal.append(s)
    return sq, maximal

def upset_cutsets(m):
    # all up-sets via non-increasing h (vertex (a,b) in U iff b >= h(a)); cut squares computed directly
    sq = [(a, b) for a in range(m) for b in range(m)]
    def rec(prefix, maxv):
        if len(prefix) == m + 1: yield tuple(prefix); return
        for v in range(maxv, -1, -1):
            prefix.append(v); yield from rec(prefix, v); prefix.pop()
    sets = set()
    for h in rec([], m + 1):
        cut = []
        for i, (a, b) in enumerate(sq):
            c = (b >= h[a]) + (b >= h[a + 1]) + (b + 1 >= h[a]) + (b + 1 >= h[a + 1])
            if c in (1, 3): cut.append(i)
        if cut: sets.add(frozenset(cut))
    sets = sorted(sets, key=len, reverse=True); maximal = []
    for s in sets:
        if not any(s <= t for t in maximal): maximal.append(s)
    return sq, maximal

def solve(sq, S, tl=600):
    A = np.zeros((len(sq), len(S)))
    for j, s in enumerate(S):
        for e in s: A[e, j] = 1
    res = milp(c=np.ones(len(S)), constraints=LinearConstraint(A, lb=np.ones(len(sq)), ub=np.inf),
               integrality=np.ones(len(S)), bounds=Bounds(0, 1), options={'time_limit': tl})
    lp = linprog(np.ones(len(S)), A_ub=-A, b_ub=-np.ones(len(sq)), bounds=[(0, None)] * len(S), method='highs')
    # dual of LP: max sum w s.t. A^T w <= 1
    du = linprog(-np.ones(len(sq)), A_ub=A.T, b_ub=np.ones(len(S)), bounds=[(0, None)] * len(sq), method='highs')
    return res, lp.fun, -du.fun, du.x

if __name__ == '__main__':
    for m in map(int, sys.argv[1:]):
        V, sides = line_dichotomies(m)
        sq, S = cutsets_from_sides(m, V, sides)
        res, lpv, duv, w = solve(sq, S)
        bnd = [i for i, (a, b) in enumerate(sq) if a in (0, m - 1) or b in (0, m - 1)]
        print(f'LINES m={m}: dichotomies={len(sides)} maximal cut-sets={len(S)} max|set|={max(map(len,S))}  '
              f'tau_m={res.fun if res.status==0 else res.status} (milp status {res.status}: {res.message[:40]})  LP={lpv:.4f}  dual={duv:.4f}  '
              f'dual weight on boundary={w[bnd].sum():.3f} interior={w.sum()-w[bnd].sum():.3f}', flush=True)
        if m <= 7:
            squ, SU = upset_cutsets(m)
            resu, lpu, duu, wu = solve(squ, SU)
            print(f'UPSETS m={m}: maximal cut-sets={len(SU)} max|set|={max(map(len,SU))}  cover number={resu.fun if resu.status==0 else resu.status}  LP={lpu:.4f}', flush=True)
